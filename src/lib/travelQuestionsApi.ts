// ---------- Questions ----------

// A category has at most ~1,800 questions: one query per category (served by idx_travel_q_cat_order) instead of
// several 1,000-row pages. The unfiltered export (admin) still pages through the table.
const PAGE_SIZE = 1000;
const CATEGORY_PAGE_SIZE = 5000;

async function fetchAllPages<T>(columns: string, categoryId?: string): Promise<T[]> {
  if (!supabase) return [];
  const out: T[] = [];
  const size = categoryId ? CATEGORY_PAGE_SIZE : PAGE_SIZE;
  for (let from = 0; ; from += size) {
    let query = supabase
      .from('travel_questions')
      .select(columns)
      .order('order_num', { ascending: true })
      .order('id', { ascending: true })
      .range(from, from + size - 1);
    if (categoryId) query = query.eq('category_id', categoryId);
    const { data, error } = await query;
    if (error) throw error;
    const rows = (data ?? []) as unknown as T[];
    out.push(...rows);
    if (rows.length < size) break;
  }
  return out;
}

export async function fetchTravelQuestions(categoryId?: string): Promise<TravelQuestion[]> {
  // public category pages are cached on the client (signed-in admin sessions always read live)
  if (categoryId) return cachedQuery(`travel_q_v1_${categoryId}`, TTL.content, () => fetchAllPages<TravelQuestion>('*', categoryId));
  return fetchAllPages<TravelQuestion>('*', categoryId);
}

export type TravelQuestionLite = Pick<TravelQuestion, 'id' | 'category_id' | 'question_en' | 'question_ar'>;

/**
 * Light version for global search. Read from the static snapshot (/data/travel_questions_lite.json, generated by
 * scripts/derive-snapshot-extras.mjs) so the search index never scans the 9k-row table in the database.
 * New questions appear in global search after the snapshot is regenerated.
 */
export async function fetchTravelQuestionsLite(): Promise<TravelQuestionLite[]> {
  try {
    const r = await fetch('/data/travel_questions_lite.json');
    return r.ok ? ((await r.json()) as TravelQuestionLite[]) : [];
  } catch {
    return [];
  }
}

/** Per-category question counts: one grouped RPC (index-covered) with a static fallback; cached on the client. */
export async function fetchTravelQuestionCounts(): Promise<Record<string, number>> {
  return cachedQuery('travel_counts_v1', TTL.content, async () => {
    const stat = async () => {
      try { const r = await fetch('/data/travel_counts.json'); return r.ok ? ((await r.json()) as Record<string, number>) : {}; } catch { return {}; }
    };
    if (!supabase) return stat();
    try {
      const { data, error } = await supabase.rpc('travel_question_counts');
      if (!error && data && typeof data === 'object') return data as Record<string, number>;
    } catch { /* fall through */ }
    return stat();
  });
}

