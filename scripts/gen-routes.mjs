// Generates functions/_lib/routes.js from the <Route path="..."> list in src/App.tsx.
// The Cloudflare function uses it to tell real pages from non-existent URLs (real HTTP 404 instead of soft-404).
// Run automatically by `npm run build`; commit the result.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync('src/App.tsx', 'utf8');
const paths = [...src.matchAll(/<Route\s+path="([^"]+)"/g)].map((m) => m[1]).filter((p) => p !== '*');
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const regs = [...new Set(paths.map((p) => '^' + p.split('/').map((seg) => (seg.startsWith(':') ? '[^/]+' : esc(seg))).join('/') + '$'))].sort();
writeFileSync(
  'functions/_lib/routes.js',
  `// Generated by scripts/gen-routes.mjs from src/App.tsx — do not edit by hand.\nexport const ROUTE_PATTERNS = [\n${regs.map((r) => `  /${r.replace(/\//g, '\\/')}/,`).join('\n')}\n];\n`,
);
console.log(regs.length, 'route patterns');
