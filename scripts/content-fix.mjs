// Exact-text content corrections for topic sections (column `sections`, JSON text).
//   node scripts/content-fix.mjs <fix.json>          → patches the static snapshot public/data/<table>.json and writes <fix>.sql
// The .sql only uses REPLACE() on the exact old sentence, so it is safe to run twice and does nothing if the text was already edited
// in the admin panel. It is run on production D1 by the "D1 content fix" workflow (manual button), never automatically.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const file = process.argv[2];
if (!file) { console.error('usage: node scripts/content-fix.mjs <fix.json>'); process.exit(1); }
const { fixes } = JSON.parse(readFileSync(file, 'utf8'));
const ROOT = new URL('..', import.meta.url).pathname;
const sqlStr = (s) => `'${s.replace(/'/g, "''")}'`;
// D1 stores sections as JSON.stringify output, so the text inside is JSON-escaped (quotes, backslashes, newlines).
const inJson = (s) => JSON.stringify(s).slice(1, -1);

let sql = '-- Generated by scripts/content-fix.mjs from ' + file.split('/').pop() + '\n';
const snapshots = new Map();
let missing = 0;
for (const f of fixes) {
  sql += `UPDATE "${f.table}" SET "sections" = REPLACE("sections", ${sqlStr(inJson(f.from))}, ${sqlStr(inJson(f.to))}) WHERE "id" = ${sqlStr(f.id)};\n`;
  const p = join(ROOT, 'public/data', f.table + '.json');
  if (!snapshots.has(p)) snapshots.set(p, JSON.parse(readFileSync(p, 'utf8')));
  const rows = snapshots.get(p);
  const row = (Array.isArray(rows) ? rows : rows.rows).find((r) => r.id === f.id);
  const text = row && JSON.stringify(row.sections);
  if (!text || !text.includes(inJson(f.from))) {
    if (text && text.includes(inJson(f.to))) continue; // already applied
    console.warn('not found in snapshot:', f.table, f.id, f.from.slice(0, 50)); missing++; continue;
  }
  const fixed = JSON.parse(text.split(inJson(f.from)).join(inJson(f.to)));
  row.sections = typeof row.sections === 'string' ? JSON.stringify(fixed) : fixed;
}
// verification: how many rows still hold an old sentence (expect 0) / hold the new one
sql += '-- check\n' + fixes.map((f) => `SELECT ${sqlStr(f.table + '/' + f.id + ': ' + f.to.slice(0, 40))} AS fix, SUM(instr("sections", ${sqlStr(inJson(f.from))}) > 0) AS old_left, SUM(instr("sections", ${sqlStr(inJson(f.to))}) > 0) AS new_present FROM "${f.table}" WHERE "id" = ${sqlStr(f.id)};`).join('\n') + '\n';
for (const [p, rows] of snapshots) writeFileSync(p, JSON.stringify(rows));
writeFileSync(file.replace(/\.json$/, '.sql'), sql);
console.log(`${fixes.length} fixes → ${file.replace(/\.json$/, '.sql')}; snapshot updated (${missing} not found)`);
if (missing) process.exit(2);
