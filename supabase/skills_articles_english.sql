<h3>Measuring blood glucose with a meter</h3>
<div class="nh-box nh-success"><p>When measuring the patient's blood sugar, do not be lazy about wiping the site with an alcohol swab, because if you skip it the reading will be wrong by about 90%. The site is usually the fingers (usually the thumb), and it is better to prick from the side of the finger to reduce the patient's pain, or to use a lancing pen, which is better. Then wipe away the first drop of blood because it is serum, and use the second drop with the glucose meter. Do not forget to press for 15 seconds on the puncture site.</p></div>

