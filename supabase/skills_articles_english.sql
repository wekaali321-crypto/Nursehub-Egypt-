<h2>🩹 6. Wound, Skin Care and Special Situations</h2>

<h3>Cold compresses</h3>
<p>The most important thing when applying cold compresses is that they must not touch the skin directly. Put an insulating material between them and the skin. For example, ice should be wrapped in cotton or a piece of gauze.</p>

<h3>Changing the dressing on a bed sore</h3>
<div class="nh-box nh-error"><p>When changing the dressing on a bed sore, do not use 10% surgical Betadine in the dressing, because it harms the weak tissues or the new cells that are still forming, so healing of the bed sore does not happen.</p></div>
<p><strong>After the sore has healed:</strong> you may find the skin color in that place a little dark, so we use bepanthen plus cream, which is an antiseptic and improves the skin color at the same time.</p>

<h3>The diabetic patient and nail cutting</h3>
<p>Do not let a diabetic patient cut his own nails and do not let anyone else cut them for him, because the clippers may cut him and he will not feel it because of peripheral neuropathy, and if bleeding happens the wound is hard to heal.</p>

<h3>Herpes simplex virus</h3>
<p>This virus causes small fluid-filled blisters on the lips and around the mouth. They may open and form a yellow infectious crust, and it takes about two to four weeks to heal on its own. The only problem with this virus is that it prefers to stay in the nerves, and it can come back in exactly the same place if the patient's immunity weakens, or the patient is under psychological stress or hormonal changes.</p>

<h3>Hibiscus tea and blood pressure</h3>
<p>Does hibiscus tea raise or lower blood pressure? Hibiscus lowers blood pressure. It contains anthocyanin, which is affected by the pH of the medium, and it also contains vitamin C, which is affected by heat. Hibiscus lowers blood pressure whether hot or cold, but boiled hibiscus loses part of its benefit because anthocyanin and vitamin C break down quickly, so its effect is lower. Cold hibiscus has a high effect and lowers blood pressure quickly.</p>

