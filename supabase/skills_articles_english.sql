<h3>Arterial blood gas (ABG): heparinize the syringe first</h3>
<p>The syringe must be heparinized before drawing the sample. Method: draw heparin to half the syringe and move it around the whole syringe, then empty it out (discard). The reason is that excess heparin causes a dilutional effect, which lowers the bicarbonate (HCO3) and carbon dioxide (PCO2) values.</p>

<h3>Liver enzymes SGOT and SGPT</h3>
<p>These are enzymes found inside liver cells, and their level rises in the blood when liver cells are damaged, as in viral hepatitis.</p>

