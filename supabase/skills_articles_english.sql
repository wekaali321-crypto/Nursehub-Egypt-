<h2>🔸 How to draw up the drug from a vial</h2>
<p>A vial is a small glass bottle with a cap of metal or plastic, tightly sealed with a rubber stopper. It is important to note that what is opened and removed is the metal or plastic cap, not the rubber stopper. Instead, the needle tip is inserted and the drug is drawn from the bottle. It may contain a sufficient amount for one dose or for several doses, and the drug inside may be a liquid or a powder that must first be dissolved before injection.</p>
<div class="nh-box nh-error"><p><strong>Common mistake:</strong> Never remove the rubber stopper of a vial. Only the metal or plastic cap is removed, then the needle is passed through the rubber.</p></div>
