<h2>💊 What you must know about the drug</h2>
<ol>
<li>The doctor's prescription.</li>
<li>Pay attention and make sure the patient has no allergy (especially with the first dose).</li>
<li>Inspect the prescribed medication for colour and clarity.</li>
<li>Always know the name of the drug.</li>
<li>Choose the equipment suitable for the prescribed medication and the injection site.</li>
<li>Indications for use.</li>
