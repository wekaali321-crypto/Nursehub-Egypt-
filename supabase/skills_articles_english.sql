<h2>🔹 How to draw up the drug from an ampoule</h2>
<p>An ampoule is a small, fine glass container whose upper part is thin, narrow and empty. It may have a mark showing where to open it to make breaking easier. It may be coloured or transparent, and you may not see the drug inside clearly. The upper part is supposed to be empty of drug when the ampoule is broken, but it may trap some of the drug. If the ampoule is broken in that state, you will not obtain the correct dose.</p>
<div class="nh-box nh-warning"><p>Gently flick the upper part of the ampoule with your finger until you are sure all the drug is in the lower part and none is trapped at the top of the ampoule.</p></div>
<table>
<thead><tr><th>Step</th><th>Action</th></tr></thead>
<tbody>
<tr><td>1</td><td>Wash your hands well with soap and water and dry them completely.</td></tr>
<tr><td>2</td><td>Gently flick the upper part of the ampoule so that all the drug falls to the lower part.</td></tr>
<tr><td>3</td><td>To break the ampoule: wrap the neck of the ampoule with an antiseptic swab, hold the neck with the finger of the hand you write with, hold the bottom of the ampoule with your other hand, and break the ampoule.</td></tr>
<tr><td>4</td><td>Place the ampoule on a flat surface, remove the syringe cap, insert the syringe tip into the drug, and pull the plunger back so that the syringe draws up the drug.</td></tr>
<tr><td>5</td><td>After drawing up, hold the syringe upright with the tip up and the plunger down, and pull the plunger down until the upper part of the syringe is empty of drug. If you find air bubbles in the syringe, tap the side of the syringe lightly with the back of your finger until the bubbles rise to the top, then press the plunger up until the drug starts to come out straight from the needle opening and reaches the correct mark for the dose you want.</td></tr>
</tbody>
</table>
