<h2>📜 Historical background</h2>
<p>Although medical syringes are simple in structure, easy to use and inexpensive, they are of great benefit to both doctor and patient, as they are the ideal and rapid means of relieving patients' pain and giving first aid to the injured.</p>
<ul>
<li><strong>The Pharaohs:</strong> People have known syringes for thousands of years. When the ancient Egyptians began embalming their kings, they suctioned out the soft tissues that were liable to decay, and then injected the molten "rabih" substance into the hollow skull through the nose. The syringe at the time was made from the hollow bone of a bear's head, thin enough to enter the nasal cavity.</li>
<li><strong>The Arabs:</strong> The Arabs knew syringes, developed them and used them in treatment. The first Arab to describe them was the surgeon Abu al-Qasim al-Zahrawi in his famous book "Al-Tasrif liman ajaza an al-ta'lif". The syringe he described was a cone-shaped tube with a sharp, thin tip and a wide base made of ivory, bone or metal, with a leather bag or an animal bladder attached to the other end. Pressing on it pushed the fluid forward. At that time the syringe was used for catheterization, to wash the bladder or introduce some substances into it, and to remove blood from the chest cavity or from wounds.</li>
<li><strong>17th century AD:</strong> Iron syringes in various shapes also appeared.</li>
<li><strong>16th century:</strong> Silver syringes were made, the doses given to the patient were marked on them, and strict conditions were set for their use, such as that nothing could be injected except under the doctor's supervision and only in specific diseases. Yet deaths after injection were many, because physicians at that time did not know about germs or sterilization methods.</li>
<li><strong>1853:</strong> Medical history records that Dr. William Ferguson was the first to make and design a syringe in a form fit for use.</li>
<li>The syringe later developed when a need appeared for graduations on the glass cylinder to determine the volume of fluid.</li>
<li><strong>Pasteur:</strong> When the scientist Pasteur discovered germs, physicians realized that the painful death ending patients' lives was not caused by the illness itself but by germs attacking the body. From then on, sterilized syringes began to be used by boiling them in water to 100 degrees. The need also became clear to make syringes from pure types of glass, free of impurities, so that drugs would not be affected by such impurities when entering the bloodstream.</li>
<li><strong>Colin Murdoch:</strong> The syringe's journey ended with the New Zealander Colin Murdoch, inventor of the single-use medical syringe that is discarded in the waste bin after use. This prevented the transmission of infectious diseases through syringes.</li>
</ul>
<h2>💉 What is an injection and what are its types?</h2>
<p>An injection is a means of introducing fluids into the body using a hollow needle and a syringe. The needle penetrates the skin to a suitable length so that the substance reaches the body. In medicine, injection is a basic method of delivering drugs.</p>
<div class="nh-box nh-callout"><p><strong>The four types of injection:</strong> into the skin (intradermal) — under the skin (subcutaneous) — into the muscle (intramuscular) — into the vein (intravenous).</p></div>
<h2>🎯 Purpose of giving medication by injection</h2>
<ol>
<li>To obtain a general and rapid effect of the drug.</li>
<li>To prevent destruction of the drug by gastric juices if it were given by mouth.</li>
<li>To give drugs when oral administration is difficult, as in unconscious patients or patients with nausea or vomiting.</li>
</ol>
