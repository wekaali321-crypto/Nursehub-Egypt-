<h2>🫁 3. Breathing, Equipment and Monitoring</h2>

<h3>Suction and oxygen</h3>
<ul>
<li>When suctioning a patient on a ventilator, do not forget to give 100% oxygen before and after suctioning, and keep the suction time to no more than 10 seconds.</li>
<li>Do not leave the patient on 100% O2 for more than one hour, because this can cause oxygen toxicity. We use 100% only before and after suction and chest physiotherapy, which are stressful procedures for the patient, for about 10 minutes.</li>
</ul>

<h3>Ventilator inoperative alarm</h3>
<div class="nh-box nh-warning"><p>One of the alarms on the ventilator is Ventilator inoperative, which means the ventilator is not working because of a technical fault. At that moment, disconnect the patient from the ventilator and ventilate with the ambu bag with (100% O2) until the patient is connected to another ventilator, then call the doctor to adjust the device according to the condition, and call the equipment staff to fix the problem.</p></div>

<h3>What is Blood Pressure?</h3>
<p>Blood pressure = Cardiac output × Peripheral resistance. It is the force of the heart pumping blood against the walls of the blood vessels, whether arteries, veins or capillaries.</p>

<h3>What is Positive End Expiratory Pressure (PEEP)?</h3>
<p>PEEP = Positive End Expiratory Pressure. It is a small amount of air that remains in the alveoli after exhalation.</p>
<p><strong>Benefit:</strong> After the breath goes out, a small amount of air stays inside the alveoli and creates positive pressure, so that the walls of the alveoli do not stick together after exhalation.</p>

<h3>The endotracheal tube (ETT) and the stylet</h3>
<p>A study of patients who needed an endotracheal tube found that using a stylet with the Endotracheal Tube (ETT) succeeds at the first attempt more often than using the tube alone, and also causes fewer complications.</p>

