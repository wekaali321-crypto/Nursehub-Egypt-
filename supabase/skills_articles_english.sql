<h3>Ceftriaxone: IV or IM?</h3>
<p>Do not confuse the intravenous and intramuscular Ceftriaxone injections. The IV solvent is water for injection (WFI). The IM solvent is Lidocaine because the injection is very painful. You can imagine what would happen if the two were swapped.</p>

<h3>Important drug warnings</h3>
<div class="nh-box nh-error"><p><strong>Penicillin:</strong> Never give a penicillin injection without a sensitivity test, even if the patient has received it more than once.</p></div>
<div class="nh-box nh-error"><p><strong>Antibiotics:</strong> If a patient needs an antibiotic, you must do an allergy test before giving it, and every time the patient takes it, because allergy can happen from the first dose, the second dose, or later.</p></div>
<div class="nh-box nh-error"><p><strong>Primperan in children:</strong> Do not give a Primperan injection to children because it causes extrapyramidal spasms that appear in the eyes, jaws and head. The solution is to give the child danset or zofran or any injection that contains Ondansetron.</p></div>
<div class="nh-box nh-error"><p><strong>No shaking when dissolving:</strong> Never shake an ampoule of streptokinase or Alteplase while dissolving it, because these drugs are very expensive, especially Alteplase. Instead, draw up the solvent that comes with it and run it gently down the wall of the vial without shaking the vial.</p></div>
<div class="nh-box nh-warning"><p><strong>Concor and asthma:</strong> Do not give Concor to an asthmatic patient. It is a beta 1 adrenergic antagonist and also acts on beta 2, causing bronchospasm, so it cannot be used in asthmatic patients.</p></div>
<div class="nh-box nh-warning"><p><strong>Azithromycin and antihistamines:</strong> Do not give azithromycin together with antihistamines because it may cause severe chest pain due to a Prolonged QT interval.</p></div>
<div class="nh-box nh-warning"><p><strong>Cordarone (amiodarone):</strong> The Cordarone ampoule causes hypotension because it contains polysorbate 80 as a solvent. The solution is to give it slowly at a controlled infusion rate, diluted in glucose solution, and this overcomes the side effect.</p></div>
<div class="nh-box nh-info"><p><strong>Enzyme drugs (trypsin and chymotrypsin):</strong> Be careful with a patient who will take a drug containing trypsin and chymotrypsin, such as Flantern and Ambezyme (as named in the source), because it must be taken one hour or half an hour before a meal, or two hours after a meal.</p></div>
<div class="nh-box nh-info"><p><strong>Vitamin K:</strong> We use vitamin K ampoules (such as Amri-K and konakion) for bleeding caused by vitamin K deficiency, such as liver failure or bleeding from anticoagulant drugs like Marevan, and the ampoule starts to work after 4 to 6 hours.</p></div>
<div class="nh-box nh-info"><p><strong>Viagra (tablet):</strong> It is used in pulmonary hypertension, meaning high blood pressure in the pulmonary artery, and it comes in strengths of 25, 50 and 100.</p></div>
<div class="nh-box nh-info"><p><strong>Asthma inhalers containing cortisone:</strong> Do not forget oral care for the asthma patient who uses cortisone inhalers such as Ventolin (ventol), seretide and flixotide. Why? To prevent mouth ulcers caused by repeated cortisone use.</p></div>

