<h3>What to do if the drug is a powder</h3>
<ol>
<li>Remove the plastic or metal cap and do not remove the rubber stopper.</li>
<li>The doctor or pharmacist will guide you to the sterile liquid used to dissolve the powder. It is either sterile distilled water that you buy from the pharmacy, or the solvent is supplied with the drug.</li>
<li>Shake the bottle well to speed up dissolving of the drug.</li>
<li>Make sure all drug particles have dissolved in the solvent.</li>
<li>Wipe the rubber top of the bottle with an antiseptic swab.</li>
<li>Draw up the prescribed amount of drug.</li>
<li>In this case you will need two syringes: one to draw up the solvent and add it to the drug powder, and another to use for the injection. One benefit is that inserting the needle into the bottle to add the solvent dulls the needle tip, which would cause pain if the same needle were used to inject the patient, so the needle is changed.</li>
<li>Check the name and dose of the drug before injecting.</li>
</ol>
