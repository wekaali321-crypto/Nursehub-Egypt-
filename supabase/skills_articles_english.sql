<h3>Why is the upper outer part of the gluteal muscle the ideal site?</h3>
<p>This site appears very suitable because:</p>
<ul>
<li>It is rich in blood capillaries, which speed up absorption of the active substance into the blood, so the patient's condition improves quickly.</li>
<li>It has relatively few sensory nerves that cause the sensation of pain at the time of injection, so the person receiving the injection in this site (the upper outer part of the gluteal muscle) feels relatively little pain.</li>
<li>This part is large and deep compared with other parts, so it tolerates relatively large injected volumes. It is therefore the suitable site for injecting more than 2 ml and 3 ml, up to 5 ml. This advantage does not apply to the arm muscle, which does not tolerate more than 3 ml of injected fluid.</li>
</ul>
