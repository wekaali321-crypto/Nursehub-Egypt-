// Generates the D1 schema (cloudflare/migrations/0001_init.sql) and the table metadata used by the
// Supabase-compatible API (functions/_lib/sbschema.js) from cloudflare/tables.txt.
import { readFileSync, writeFileSync } from 'node:fs';
const lines = readFileSync('cloudflare/tables.txt', 'utf8').trim().split('\n');
const schema = {};
let sql = '-- Generated by cloudflare/gen.mjs — do not edit by hand.\n';
const NOW = "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))";
const q = (n) => `"${n}"`;
for (const line of lines) {
  const [table, pk, colstr] = line.split('|');
  const cols = {};
  const defs = [];
  for (const c of colstr.split(',')) {
    const m = /^([^:]+):([a-z]+)(!?)$/.exec(c);
    const [, name, type, req] = m;
    cols[name] = type;
    const sqlType = { text: 'TEXT', ts: 'TEXT', int: 'INTEGER', num: 'REAL', bool: 'INTEGER', json: 'TEXT', arr: 'TEXT' }[type];
    let d = `${q(name)} ${sqlType}`;
    if (name === pk) {
      if (type === 'int') d += ' PRIMARY KEY AUTOINCREMENT';
      else d += ` PRIMARY KEY${req ? '' : " DEFAULT (lower(hex(randomblob(16))))"}`;
    } else {
      if (type === 'ts') d += ` DEFAULT ${NOW}`;
      else if (type === 'bool') d += ' DEFAULT 0';
      if (req && type !== 'ts' && type !== 'bool') d += ' NOT NULL';
    }
    defs.push(d);
  }
  schema[table] = { pk, cols };
  sql += `CREATE TABLE IF NOT EXISTS ${q(table)} (\n  ${defs.join(',\n  ')}\n);\n`;
}
sql += `
CREATE INDEX IF NOT EXISTS idx_site_visits_created ON site_visits(created_at);
CREATE INDEX IF NOT EXISTS idx_site_visits_visitor ON site_visits(visitor_id, created_at);
CREATE INDEX IF NOT EXISTS idx_site_pings_created ON site_pings(created_at);
CREATE INDEX IF NOT EXISTS idx_site_installs_visitor ON site_installs(visitor_id);
CREATE INDEX IF NOT EXISTS idx_articles_slug ON articles(slug);
CREATE INDEX IF NOT EXISTS idx_comments_article ON comments(article_id);
CREATE INDEX IF NOT EXISTS idx_bookmarks_user ON bookmarks(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);

-- Auth (replaces Supabase Auth)
CREATE TABLE IF NOT EXISTS auth_users (
  id TEXT PRIMARY KEY DEFAULT (lower(hex(randomblob(16)))),
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT,
  name TEXT,
  provider TEXT DEFAULT 'email',
  meta TEXT DEFAULT '{}',
  created_at TEXT DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS auth_refresh (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS auth_codes (
  code TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  challenge TEXT,
  expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS media_objects (
  path TEXT PRIMARY KEY,
  bucket TEXT NOT NULL,
  content_type TEXT,
  size INTEGER,
  created_at TEXT DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS media_chunks (
  key TEXT NOT NULL,
  idx INTEGER NOT NULL,
  data BLOB NOT NULL,
  PRIMARY KEY (key, idx)
);
`;
// upsert(onConflict:'endpoint') from the push subscribe flow needs a UNIQUE index
sql += '\nCREATE UNIQUE INDEX IF NOT EXISTS idx_push_endpoint ON push_subscriptions(endpoint);\n';
writeFileSync('cloudflare/migrations/0001_init.sql', sql);
writeFileSync('functions/_lib/sbschema.js', `// Generated by cloudflare/gen.mjs — do not edit by hand.\nexport const SCHEMA = ${JSON.stringify(schema)};\n`);
console.log(Object.keys(schema).length, 'tables');
